#!/usr/bin/env python3
"""Build one convex hull per chess piece type for MoveIt collision (offline)."""

from __future__ import annotations

import argparse
import struct
from pathlib import Path

import numpy as np
from scipy.spatial import ConvexHull

PIECE_TYPES = ('pawn', 'rook', 'knight', 'bishop', 'queen', 'king')


def y_up_to_z_up(vertices: np.ndarray) -> np.ndarray:
    """Staunton STLs use Y-up; MoveIt / REP-103 use Z-up."""
    out = vertices.copy()
    out[:, 0] = vertices[:, 0]
    out[:, 1] = vertices[:, 2]
    out[:, 2] = vertices[:, 1]
    return out


def load_binary_stl(path: Path) -> np.ndarray:
    """Load vertices from binary STL (handles SolidWorks-style 80-byte header)."""
    data = path.read_bytes()
    if len(data) < 84:
        raise ValueError(f'{path}: file too small')
    tri_count = struct.unpack_from('<I', data, 80)[0]
    expected = 84 + tri_count * 50
    if len(data) < expected:
        raise ValueError(f'{path}: truncated binary STL ({tri_count} triangles)')
    verts: list[tuple[float, float, float]] = []
    offset = 84
    for _ in range(tri_count):
        offset += 12  # normal
        for __ in range(3):
            x, y, z = struct.unpack_from('<fff', data, offset)
            verts.append((x, y, z))
            offset += 12
        offset += 2  # attribute
    return np.asarray(verts, dtype=float)


def write_binary_stl(path: Path, vertices: np.ndarray, faces: np.ndarray, label: str) -> None:
    header = f'collision {label}'[:80].encode('ascii', errors='ignore').ljust(80, b' ')
    body = bytearray()
    body.extend(struct.pack('<I', len(faces)))
    for i0, i1, i2 in faces:
        v0, v1, v2 = vertices[i0], vertices[i1], vertices[i2]
        normal = np.cross(v1 - v0, v2 - v0)
        norm = float(np.linalg.norm(normal))
        if norm > 0.0:
            normal /= norm
        else:
            normal = np.zeros(3)
        body.extend(struct.pack('<3f', *normal))
        for v in (v0, v1, v2):
            body.extend(struct.pack('<3f', *v))
        body.extend(struct.pack('<H', 0))
    path.write_bytes(header + body)


def center_mesh_xy_on_base(vertices: np.ndarray) -> np.ndarray:
    """Shift so Z-min is 0 and XY centroid uses lower third of piece (base region)."""
    out = vertices.copy()
    z_min = float(out[:, 2].min())
    z_max = float(out[:, 2].max())
    out[:, 2] -= z_min
    z_span = max(z_max - z_min, 1e-9)
    base_mask = out[:, 2] <= z_span * 0.25
    if not np.any(base_mask):
        base_mask = np.ones(len(out), dtype=bool)
    cx = float(out[base_mask, 0].mean())
    cy = float(out[base_mask, 1].mean())
    out[:, 0] -= cx
    out[:, 1] -= cy
    return out


def convex_hull_mesh(vertices: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    hull = ConvexHull(vertices)
    remap = np.full(len(vertices), -1, dtype=int)
    remap[hull.vertices] = np.arange(len(hull.vertices))
    hull_verts = vertices[hull.vertices]
    hull_faces = remap[hull.simplices]
    return hull_verts, hull_faces


def process_piece(
    source: Path,
    dest: Path,
    *,
    scale: float,
) -> dict[str, float]:
    verts = y_up_to_z_up(load_binary_stl(source)) * float(scale)
    verts = center_mesh_xy_on_base(verts)
    hull_verts, hull_faces = convex_hull_mesh(verts)
    write_binary_stl(dest, hull_verts, hull_faces, dest.stem)
    return {
        'height_m': float(hull_verts[:, 2].max()),
        'base_diameter_m': float(
            max(
                hull_verts[:, 0].max() - hull_verts[:, 0].min(),
                hull_verts[:, 1].max() - hull_verts[:, 1].min(),
            )
        ),
        'triangles': int(len(hull_faces)),
        'vertices': int(len(hull_verts)),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        '--source-dir',
        type=Path,
        default=Path(__file__).resolve().parent.parent / 'meshes' / 'chess_pieces' / 'staunton',
    )
    parser.add_argument(
        '--output-dir',
        type=Path,
        default=Path(__file__).resolve().parent.parent / 'meshes' / 'chess_pieces' / 'collision_hulls',
    )
    parser.add_argument(
        '--scale',
        type=float,
        default=0.001,
        help='Multiply raw STL mm coordinates to metres (default 0.001)',
    )
    args = parser.parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)

    meta_lines = ['# Auto-generated by build_chess_collision_hulls.py', 'pieces:']
    for piece in PIECE_TYPES:
        src = args.source_dir / f'{piece}.stl'
        if not src.is_file():
            raise SystemExit(f'missing source mesh: {src} (run fetch_chess_piece_meshes.sh)')
        stats = process_piece(src, args.output_dir / f'{piece}.stl', scale=args.scale)
        meta_lines.append(f'  {piece}:')
        meta_lines.append(f'    file: {piece}.stl')
        for key, val in stats.items():
            if isinstance(val, float):
                meta_lines.append(f'    {key}: {val:.6f}')
            else:
                meta_lines.append(f'    {key}: {val}')
        print(
            f'{piece}: {stats["triangles"]} tris, '
            f'h={stats["height_m"]*1000:.1f}mm base={stats["base_diameter_m"]*1000:.1f}mm'
        )

    (args.output_dir / 'piece_mesh.yaml').write_text('\n'.join(meta_lines) + '\n', encoding='utf-8')
    print(f'Wrote collision hulls to {args.output_dir}')


if __name__ == '__main__':
    main()
